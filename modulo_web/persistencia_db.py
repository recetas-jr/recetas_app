def db_cargar_receta_detalle(receta_id):

    conn = get_connection()

    cur = conn.cursor()

    cur.execute("""

        SELECT

            r.id,

            r.plato_id,

            r.raciones_base,

            r.preparacion,

            r.elaboracion,

            r.presentacion,

            r.nutricion,

            p.nombre AS plato_nombre,

            p.foto AS plato_foto

        FROM recetas_maestro r

        JOIN platos p ON p.id = r.plato_id

        WHERE r.id = %s

    """, (receta_id,))

    fila = cur.fetchone()

    if not fila:

        conn.close()

        return None

    receta = {

        "id": fila["id"],

        "plato_id": fila["plato_id"],

        "plato_nombre": fila["plato_nombre"],

        "plato_foto": fila["plato_foto"],

        "raciones_base": fila["raciones_base"],

        "preparacion": fila["preparacion"] or "",

        "elaboracion": fila["elaboracion"] or "",

        "presentacion": fila["presentacion"] or "",

        "nutricion": fila["nutricion"] or "",

        "textos": {

            "preparacion": fila["preparacion"] or "",

            "elaboracion": fila["elaboracion"] or "",

            "presentacion": fila["presentacion"] or "",

            "nutricion": fila["nutricion"] or ""

        },

        "ingredientes": []

    }

    cur.execute("""

        SELECT

            ri.ingrediente_id,

            i.nombre AS ingrediente_nombre,

            ri.cantidad,

            ri.unidad_codigo_presentacion,

            ri.expresion_c_texto,

            ri.cantidad_captura,

            ri.rol,

            ri.deco_captura,

            u.codigo AS unidad_codigo,

            u.nombre AS unidad_nombre,

            ri.cantidad_captura,

            ri.expresion_c_texto

        FROM recetas_ingredientes ri

        JOIN ingredientes i ON i.id = ri.ingrediente_id

        JOIN unidades u ON u.id = i.unidad_id

        WHERE ri.receta_id = %s

        ORDER BY i.nombre

    """, (receta_id,))

    filas_ing = cur.fetchall()

    conn.close()

    for f in filas_ing:

        receta["ingredientes"].append({

            "ingrediente_id": f["ingrediente_id"],

            "nombre": f["ingrediente_nombre"],

            "cantidad": f["cantidad"],

            "cantidad_captura": f["cantidad_captura"],

            "unidad_codigo_presentacion": f["unidad_codigo_presentacion"],

            "rol": f["rol"],

            "deco_captura": f["deco_captura"],

            "unidad_codigo": f["unidad_codigo"],

            "unidad_nombre": f["unidad_nombre"],

            "cantidad_captura": f["cantidad_captura"],

            "expresion_c_texto": f["expresion_c_texto"]
        })

    return receta


def db_guardar_version_publica(receta_id):

    # Obtener una copia completa de la receta maestra.
    receta = db_cargar_receta_detalle(receta_id)

    # No crear ni sobrescribir una publicación si la receta no existe.
    if receta is None:
        return False

    conn = get_connection()

    try:
        cur = conn.cursor()

        cur.execute(
            """
            INSERT INTO recetas_publicadas (
                receta_id,
                contenido,
                fecha_actualizacion
            )
            VALUES (%s, %s, CURRENT_TIMESTAMP)
            ON CONFLICT (receta_id)
            DO UPDATE SET
                contenido = EXCLUDED.contenido,
                fecha_actualizacion = CURRENT_TIMESTAMP
            """,
            (int(receta_id), Jsonb(
                receta,
                dumps=_json_dumps_decimal
            ))
        )

        conn.commit()
        return True

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


