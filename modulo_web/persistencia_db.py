def db_cargar_unidades_disponibles_por_ingrediente(ingrediente_id):
    """
    Devuelve las unidades disponibles para un ingrediente.

    Esta función adapta la información del Motor de Conversión
    al formato que necesita la interfaz web.

    No realiza conversiones.

    No modifica información.

    Devuelve únicamente los datos necesarios para poblar el
    selector de unidades durante la captura de recetas.
    """

    conn = get_connection()

    cur = conn.cursor()

    cur.execute(
        """
        SELECT
            u.id,
            u.codigo,
            u.nombre
        FROM ingredientes i
        JOIN unidades u
            ON u.id = i.unidad_id
        WHERE i.id = %s
        """,
        (ingrediente_id,)
    )

    unidad_base = cur.fetchone()

    conn.close()

    equivalencias = db_cargar_equivalencias(ingrediente_id)

    print(
        "DEBUG UNIDADES DISPONIBLES:",
        ingrediente_id,
        equivalencias
    )

    unidades = []

    if unidad_base:

        unidades.append({
            "unidad_id": unidad_base["id"],
            "codigo": unidad_base["codigo"],
            "nombre": unidad_base["nombre"]
        })

    for equivalencia in equivalencias:

        unidades.append({
            "unidad_id": equivalencia["unidad_id"],
            "codigo": equivalencia["codigo"],
            "nombre": equivalencia["nombre"]
        })

    return unidades


def db_cargar_unidades_disponibles_por_ingredientes(ingrediente_ids):
    """
    Carga las unidades base y equivalencias de varios ingredientes
    mediante una sola conexión y una consulta agrupada.
    No realiza conversiones ni modifica datos.
    """

    ids = list(dict.fromkeys(ingrediente_ids))

    resultado = {ingrediente_id: [] for ingrediente_id in ids}

    if not ids:
        return resultado

    conn = get_connection()

    try:
        cur = conn.cursor()

        cur.execute(
            """
            SELECT
                i.id AS ingrediente_id,
                u.id AS unidad_id,
                u.codigo,
                u.nombre,
                0 AS tipo_orden
            FROM ingredientes i
            JOIN unidades u
                ON u.id = i.unidad_id
            WHERE i.id = ANY(%s)

            UNION ALL

            SELECT
                e.ingrediente_id,
                u.id AS unidad_id,
                u.codigo,
                u.nombre,
                1 AS tipo_orden
            FROM ingredientes_equivalencias e
            JOIN unidades u
                ON u.id = e.unidad_id
            WHERE e.ingrediente_id = ANY(%s)

            ORDER BY ingrediente_id, tipo_orden, nombre
            """,
            (ids, ids)
        )

        for fila in cur.fetchall():
            resultado[fila["ingrediente_id"]].append({
                "unidad_id": fila["unidad_id"],
                "codigo": fila["codigo"],
                "nombre": fila["nombre"]
            })

    finally:
        conn.close()

    return resultado


