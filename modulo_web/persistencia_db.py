def _json_dumps_decimal(obj):

    prefijo = f"__DECIMAL_{uuid.uuid4().hex}_"
    decimales = {}

    def convertir(valor):

        if isinstance(valor, Decimal):
            if not valor.is_finite():
                raise ValueError(
                    "No se puede serializar un Decimal no finito."
                )

            marcador = f"{prefijo}{len(decimales)}__"
            decimales[marcador] = format(valor, "f")
            return marcador

        if isinstance(valor, dict):
            return {
                clave: convertir(dato)
                for clave, dato in valor.items()
            }

        if isinstance(valor, (list, tuple)):
            return [convertir(elemento) for elemento in valor]

        return valor

    resultado = json.dumps(
        convertir(obj),
        ensure_ascii=False
    )

    for marcador, numero in decimales.items():
        resultado = resultado.replace(
            json.dumps(marcador),
            numero
        )

    return resultado


def get_connection():

    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "La variable de entorno DATABASE_URL no está configurada."
        )

    conn = psycopg.connect(
        database_url,
        row_factory=dict_row
    )

    return conn


def init_db():

    conn = get_connection()
    cur = conn.cursor()

    # ----------------------------
    # TABLAS BASE
    # ----------------------------

    cur.execute("""
    CREATE TABLE IF NOT EXISTS tipos_plato (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT NOT NULL UNIQUE
    );
    """)

    cur.execute("""
    CREATE TABLE IF NOT EXISTS unidades (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        codigo TEXT NOT NULL UNIQUE,
        nombre TEXT NOT NULL
    );
    """)

    cur.execute("""
    CREATE TABLE IF NOT EXISTS platos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT NOT NULL UNIQUE,
        tipo_plato_id INTEGER,
        activo BOOLEAN NOT NULL DEFAULT TRUE,
        foto TEXT,
        cantidad_racion NUMERIC,
        unidad_racion_id INTEGER,
        FOREIGN KEY (tipo_plato_id) REFERENCES tipos_plato(id),
        FOREIGN KEY (unidad_racion_id) REFERENCES unidades(id)
    );
    """)

    cur.execute("""
    CREATE TABLE IF NOT EXISTS ingredientes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre TEXT NOT NULL UNIQUE,
        unidad_id INTEGER NOT NULL,
        activo BOOLEAN NOT NULL DEFAULT TRUE,
        FOREIGN KEY (unidad_id) REFERENCES unidades(id)
    );
    """)

    # ----------------------------
    # TABLAS DEL MASTER DE RECETAS
    # ----------------------------

    cur.execute("""
    CREATE TABLE IF NOT EXISTS recetas_maestro (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        plato_id INTEGER NOT NULL,
        raciones_base INTEGER NOT NULL,
        preparacion TEXT,
        elaboracion TEXT,
        presentacion TEXT,
        nutricion TEXT,
        visible_web BOOLEAN NOT NULL DEFAULT TRUE,
        FOREIGN KEY (plato_id) REFERENCES platos(id)
    );
    """)

    cur.execute("""
    CREATE TABLE IF NOT EXISTS expresiones_culinarias (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        unidad_codigo TEXT NOT NULL,
        expresion TEXT NOT NULL,
        factor NUMERIC NOT NULL,
        orden INTEGER NOT NULL,
        activo BOOLEAN NOT NULL DEFAULT TRUE,
        UNIQUE (unidad_codigo, expresion)
    );
    """)

    cur.execute("""
    CREATE TABLE IF NOT EXISTS recetas_ingredientes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        receta_id INTEGER NOT NULL,
        ingrediente_id INTEGER NOT NULL,
        cantidad NUMERIC NOT NULL,
        rol TEXT NOT NULL,
        unidad_codigo_presentacion TEXT,
        expresion_id INTEGER,
        expresion_c_id INTEGER,
        expresion_c_texto TEXT,
        cantidad_captura TEXT,
        expresion_d_id INTEGER,
        expresion_d_texto TEXT,
        deco_captura TEXT,
        FOREIGN KEY (receta_id) REFERENCES recetas_maestro(id),
        FOREIGN KEY (ingrediente_id) REFERENCES ingredientes(id),
        FOREIGN KEY (expresion_id) REFERENCES expresiones_culinarias(id)
    );
    """)

    cur.execute("""
    CREATE TABLE IF NOT EXISTS recetas_detalle (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        receta_id INTEGER NOT NULL UNIQUE,
        preparacion TEXT,
        elaboracion TEXT,
        presentacion TEXT,
        nutricion TEXT,
        FOREIGN KEY (receta_id) REFERENCES recetas_maestro(id)
    );
    """)

    # ----------------------------
    # CONTACTOS WEB
    # ----------------------------

    cur.execute("""
    CREATE TABLE IF NOT EXISTS contactos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        fecha TEXT NOT NULL,
        nombre TEXT NOT NULL,
        correo TEXT NOT NULL,
        asunto TEXT NOT NULL,
        mensaje TEXT NOT NULL,
        atendido BOOLEAN NOT NULL DEFAULT FALSE
    );
    """)

    conn.commit()
    conn.close()

